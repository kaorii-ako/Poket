CELL_W, CELL_H = 5, 8


def bits(ch):
    """-> list of CELL_H rows, each a list of CELL_W 0/1."""
    rows = G[ch].split('/')
    assert len(rows) == CELL_H, ch
    out = []
    for r in rows:
        assert len(r) == CELL_W, (ch, r)
        out.append([1 if c == '#' else 0 for c in r])
    return out


def glyph(ch, proportional):
    """-> (width, rows) trimmed to the inked columns when proportional."""
    b = bits(ch)
    if not proportional:
        return CELL_W, b
    cols = [x for x in range(CELL_W) if any(b[y][x] for y in range(CELL_H))]
    if not cols:                                   # space
        return 3, [[0] * 3 for _ in range(CELL_H)]
    x0, x1 = cols[0], cols[-1]
    return x1 - x0 + 1, [row[x0:x1 + 1] for row in b]


